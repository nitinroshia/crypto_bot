#!/usr/bin/env python3
"""Reference implementation of the amended S1/S2 stability check (Work Order 1.5, section 3).

PURPOSE. This file is the unambiguous definition of the statistic. The developer owns the production
implementation (blocks.py / stability_check.py) and should NOT copy this wholesale: reuse your own
predictor/target code, registry hooks and CLI conventions. Two things are mandatory, though:
  (1) the production statistic must match this definition, and
  (2) the production code must pass the acceptance tests in --self-test (adapt them to your harness).

WHY THE OLD TEST WAS REPLACED (simulated by the mathematician, 2026-10): per-block OLS with its own
intercept on an overlapping, persistent predictor (x_40 reuses 39 of 40 days) is biased. On pure noise
85% of 90-origin blocks came out with a NEGATIVE slope, the mean combined Stouffer z was about -7.6, and
the opposite-block veto fired in 100% of null paths; with a very strong injected edge (pooled HAC t about
+11) the old check still passed only 0.7% of paths. Removing the per-block intercept did not fix it.
A circular time-shift null is also invalid for S1 (predictor and target are built from the same price
series, so the observed alignment is structurally different from a shifted one).

DEFINITION (identical for S1 and S2 except the null generator):
  blocks   : B full, non-overlapping blocks of n origins (n = 90 days) tiled from the family's first origin
             of the COMMON origin set; the final partial block is dropped.
  score    : c_b = d * sum_{t in block b} xt * yt, where xt, yt are deviations from their means over the
             WHOLE common origin set (global centring, no per-block intercept), and
             y is the forward return divided by trailing 30-day sd of daily log returns at the origin.
             d = +1 for S1 (pre-registered direction positive), d = -1 for S2 (negative).
  null     : R = 2000 replicates generated by the pipeline's own code path
             S1: stationary block bootstrap of the daily log returns (mean block length 20 days),
                 predictor and target REBUILT from each resampled path at the same origin positions;
             S2: circular time-shift of the funding-rank vector against the target vector by a random
                 offset of at least 300 settlements from zero (the rank vector itself is computed once).
  combine  : mu_b, sd_b = mean and std of c_b over the replicates; s_b = (c_b - mu_b) / sd_b;
             T = sum_b s_b / sqrt(B); p_stab = (1 + #{replicates with T_r >= T_obs}) / (R + 1),
             where T_r uses the same mu_b and sd_b.
  pass     : p_stab < 0.05 (then Holm across candidates, per pair, exactly as before).
  retired  : the opposite-block veto. At 90 origins a single block has almost no power, so the veto can only
             fire by chance; calibrated it still false-vetoed 11-16% of null paths for S2. LOYO (section 6,
             non-stationarity rule) and the economic gate's block rule already cover regime flips.
"""
import sys
import numpy as np


# ----------------------------------------------------------------------------- core statistic
def block_scores(x, y, B, n, d):
    """x, y: (..., >=B*n) arrays over the common origin set. Returns (..., B) block scores."""
    N = B * n
    x = x[..., :N]
    y = y[..., :N]
    xc = x - x.mean(-1, keepdims=True)
    yc = y - y.mean(-1, keepdims=True)
    return d * (xc * yc).reshape(*x.shape[:-1], B, n).sum(-1)


def combine(c_obs, c_null):
    """c_obs (B,), c_null (R, B) -> (T_obs, p_stab, s_obs)."""
    B = len(c_obs)
    mu, sd = c_null.mean(0), c_null.std(0)
    s_obs = (c_obs - mu) / sd
    T_obs = s_obs.sum() / np.sqrt(B)
    T_null = ((c_null - mu) / sd).sum(1) / np.sqrt(B)
    p = (1 + (T_null >= T_obs).sum()) / (len(T_null) + 1)
    return T_obs, p, s_obs


# ----------------------------------------------------------------------------- S1 (bootstrap null)
def s1_xy(r, idx, L=40, h=5, std_y=True):
    """r: (..., T) daily log returns. idx: integer positions of the origins (closes). Returns x, y."""
    lnC = np.cumsum(r, axis=-1)
    c2 = np.cumsum(r ** 2, axis=-1)
    s1 = lnC[..., idx] - lnC[..., idx - 30]
    s2 = c2[..., idx] - c2[..., idx - 30]
    sd30 = np.sqrt(np.maximum((s2 - s1 ** 2 / 30) / 29, 1e-18))
    x = (lnC[..., idx] - lnC[..., idx - L]) / sd30
    y = lnC[..., idx + h] - lnC[..., idx]
    return x, (y / sd30 if std_y else y)


def stationary_bootstrap_idx(R, T, mean_block, rng):
    restart = rng.random((R, T)) < 1.0 / mean_block
    restart[:, 0] = True
    starts = rng.integers(0, T, (R, T))
    tt = np.arange(T)[None, :]
    base = np.maximum.accumulate(np.where(restart, tt, 0), axis=1)
    sv = np.take_along_axis(starts, base, axis=1)
    return (sv + (tt - base)) % T


def stability_s1(r, idx, B, n, d=+1, R=2000, mean_block=20, L=40, h=5, seed=0, chunk=250):
    rng = np.random.default_rng(seed)
    x0, y0 = s1_xy(r, idx, L, h)
    c_obs = block_scores(x0, y0, B, n, d)
    c_null = np.empty((R, B))
    done = 0
    while done < R:
        m = min(chunk, R - done)
        bi = stationary_bootstrap_idx(m, len(r), mean_block, rng)
        xb, yb = s1_xy(r[bi], idx, L, h)
        c_null[done:done + m] = block_scores(xb, yb, B, n, d)
        done += m
    return combine(c_obs, c_null) + (c_obs,)


# ----------------------------------------------------------------------------- S2 (time-shift null)
def stability_s2(rank, ystd, B, n, d=-1, R=2000, min_shift=300, seed=0):
    rng = np.random.default_rng(seed)
    N = B * n
    xc = rank[:N] - rank[:N].mean()
    yc = ystd[:N] - ystd[:N].mean()
    xb = np.zeros((B, N))
    for b in range(B):
        xb[b, b * n:(b + 1) * n] = xc[b * n:(b + 1) * n]
    # circular cross-correlation: C[b, k] = sum_i xb[b, i] * yc[(i + k) % N]
    C = d * np.fft.irfft(np.conj(np.fft.rfft(xb, axis=1)) * np.fft.rfft(yc)[None, :], n=N, axis=1)
    c_obs = C[:, 0]
    allowed = np.arange(min_shift, N - min_shift + 1)
    ks = rng.choice(allowed, size=min(R, len(allowed)), replace=False)
    return combine(c_obs, C[:, ks].T) + (c_obs,)


# ----------------------------------------------------------------------------- synthetic generators
def sim_s1(rng, P, B, n, kind="gauss", a=0.0, L=40, h=5, phi=0.98):
    N = B * n
    T = N + L + h + 5
    if kind == "gauss":
        r = 0.03 * rng.standard_normal((P, T))
    else:  # fat tails (t3) + persistent stochastic volatility
        z = rng.standard_t(3, (P, T)) / np.sqrt(3.0)
        v = np.zeros((P, T))
        eta = 0.2 * rng.standard_normal((P, T))
        for t in range(1, T):
            v[:, t] = 0.98 * v[:, t - 1] + eta[:, t]
        r = 0.03 * np.exp(0.5 * v) * z
    if a:  # latent slowly-moving drift => genuine momentum
        m = np.zeros((P, T))
        e2 = rng.standard_normal((P, T)) * np.sqrt(1 - phi ** 2)
        for t in range(1, T):
            m[:, t] = phi * m[:, t - 1] + e2[:, t]
        r = r + a * m
    return r, np.arange(L, L + N)


def sim_s2(rng, P, B, n, kind="gauss", a=0.0, W=270, H=9):
    N = B * n
    T = W + N + H + 100
    f = np.zeros((P, T))
    eps = rng.standard_normal((P, T))
    for t in range(1, T):
        f[:, t] = 0.98 * f[:, t - 1] + eps[:, t]
    from numpy.lib.stride_tricks import sliding_window_view
    win = sliding_window_view(f[:, :-1], W, axis=1)
    cur = f[:, W:]
    rank = ((win < cur[..., None]).sum(-1) + 0.5 * (win == cur[..., None]).sum(-1)) / W
    if kind == "gauss":
        r = 0.015 * rng.standard_normal((P, T))
    else:
        z = rng.standard_t(3, (P, T)) / np.sqrt(3.0)
        v = np.zeros((P, T))
        eta = 0.2 * rng.standard_normal((P, T))
        for t in range(1, T):
            v[:, t] = 0.98 * v[:, t - 1] + eta[:, t]
        r = 0.015 * np.exp(0.5 * v) * z
    if a:
        drift = np.zeros((P, T))
        drift[:, W + 1:] = -a * (rank[:, :-1] - 0.5)
        r = r + drift
    cs = np.cumsum(r, axis=1)
    c2 = np.cumsum(r ** 2, axis=1)
    idx = np.arange(W, W + N)
    sd = np.sqrt(np.maximum((c2[:, idx] - c2[:, idx - 90]) / 90, 1e-18))
    return rank[:, :N], (cs[:, idx + H] - cs[:, idx]) / sd


# ----------------------------------------------------------------------------- acceptance tests
def self_test(P=60, R=500, full=False):
    """Acceptance bands (Work Order 1.5, section 4). --full uses P=200, R=1000 (about 15-25 minutes)."""
    if full:
        P, R = 200, 1000
    rng = np.random.default_rng(12345)
    B1, n1 = 30, 90
    B2, n2 = 22, 270
    res = {}

    def s1_rate(kind, a):
        r, idx = sim_s1(rng, P, B1, n1, kind, a)
        return np.mean([stability_s1(r[i], idx, B1, n1, +1, R=R, seed=i)[1] < 0.05 for i in range(P)])

    def s2_rate(kind, a):
        x, y = sim_s2(rng, P, B2, n2, kind, a)
        return np.mean([stability_s2(x[i], y[i], B2, n2, -1, R=R, seed=i)[1] < 0.05 for i in range(P)])

    tests = [
        ("S1 null, Gaussian iid            false-pass <= 0.07", lambda: s1_rate("gauss", 0.0), lambda v: v <= 0.07),
        ("S1 null, t3 + volatility cluster false-pass <= 0.07", lambda: s1_rate("t3sv", 0.0), lambda v: v <= 0.07),
        ("S1 edge a=0.006 (pooled t ~ 5)   pass >= 0.70", lambda: s1_rate("gauss", 0.006), lambda v: v >= 0.70),
        ("S1 edge a=0.012 (pooled t ~ 11)  pass >= 0.95", lambda: s1_rate("gauss", 0.012), lambda v: v >= 0.95),
        ("S2 null, Gaussian                false-pass <= 0.07", lambda: s2_rate("gauss", 0.0), lambda v: v <= 0.07),
        ("S2 null, t3 + volatility cluster false-pass <= 0.07", lambda: s2_rate("t3sv", 0.0), lambda v: v <= 0.07),
        ("S2 edge a=0.003 (corr ~ -0.16)   pass >= 0.80", lambda: s2_rate("gauss", 0.003), lambda v: v >= 0.80),
    ]
    ok = True
    for name, run, check in tests:
        v = run()
        good = check(v)
        ok &= bool(good)
        print(f"  {'PASS' if good else 'FAIL'}  {name}   observed {v:.3f}", flush=True)
    print("ALL STABILITY ACCEPTANCE TESTS PASSED" if ok else "STABILITY ACCEPTANCE TESTS FAILED")
    return ok


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(0 if self_test(full="--full" in sys.argv) else 1)
    print(__doc__)
